/**
 * Helper to analyze teaching methods and strategies, and find the most suitable educational game
 */
export function analyzeAndRecommendGame(
  methodsStr?: string,
  strategyStr?: string,
  grade: Grade = 4,
  subject: string = 'គណិតវិទ្យា'
): EducationalGame {
  const mLower = (methodsStr || '').toLowerCase();
  const sLower = (strategyStr || '').toLowerCase();

  // 1. If grade 1 or 2, favor physical, engaging, simple games
  if (grade <= 2) {
    if (subject.includes('ភាសា')) {
      return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'hot-potato-ball') || PRIMARY_EDUCATIONAL_GAMES[1];
    }
    return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'lucky-wheel') || PRIMARY_EDUCATIONAL_GAMES[0];
  }

  // 2. If strategy mentions Think-Pair-Share or Hands-on
  if (sLower.includes('think-pair-share') || sLower.includes('ចាប់គូ')) {
    if (grade <= 4) {
      return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'lucky-wheel') || PRIMARY_EDUCATIONAL_GAMES[0];
    } else {
      return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'board-relay') || PRIMARY_EDUCATIONAL_GAMES[3];
    }
  }

  // 3. If strategy mentions Gallery Walk or TEC template
  if (sLower.includes('gallery walk') || sLower.includes('វិចិត្រសាល') || mLower.includes('tec')) {
    return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'gallery-walk-challenge') || PRIMARY_EDUCATIONAL_GAMES[6];
  }

  // 4. If problem solving or inquiry based
  if (mLower.includes('ibl') || mLower.includes('រិះរក') || mLower.includes('pbl') || mLower.includes('បញ្ហា')) {
    if (subject.includes('វិទ្យាសាស្ត្រ')) {
      return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'matching-relay') || PRIMARY_EDUCATIONAL_GAMES[2];
    }
    return PRIMARY_EDUCATIONAL_GAMES.find(g => g.id === 'cambodian-banana-bird') || PRIMARY_EDUCATIONAL_GAMES[8];
  }

  // 5. Default by grade and subject
  const matched = PRIMARY_EDUCATIONAL_GAMES.find(g => 
    g.grades.includes(grade) && g.subjects.some(s => subject.includes(s) || s.includes(subject))
  );

  return matched || PRIMARY_EDUCATIONAL_GAMES[0];
}
